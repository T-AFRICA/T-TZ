import type { CategorySection } from "@tronic/types";

/**
 * The storefront's category list (packages/country-config, the eight
 * navbar sections) as rows for country migration 0018, which fills the
 * database with it so the website can read its categories from there.
 *
 * Shop by Use is not a category (its groups are use cases, products point
 * to them in product_use_cases), so it is left out.
 *
 * The block is pasted into the migration between the BEGIN/END markers;
 * tests/taxonomy-sql.test.ts fails when the two differ.
 */

const literal = (value: string | null | undefined) => (value === null || value === undefined ? "null" : `'${value.replaceAll("'", "''")}'`);

export const TAXONOMY_BEGIN = "-- BEGIN TAXONOMY (generated by database/client/scripts/taxonomy-sql.ts from packages/country-config/src/tz/categories.ts)";
export const TAXONOMY_END = "-- END TAXONOMY";

/** One row per subcategory, or per group without subcategories: category, its order, group, its order, subcategory, its order. */
export function buildTaxonomyRows(sections: readonly CategorySection[]): string {
  const rows: string[] = [];
  sections
    .filter((section) => (section.kind ?? "department") === "department")
    .forEach((section, categoryOrder) => {
      const category = [literal(section.slug), literal(section.name), literal(section.description), String(categoryOrder)];
      if (section.groups.length === 0) rows.push(`  (${[...category, "null", "null", "null", "null", "null", "null"].join(", ")})`);
      section.groups.forEach((group, groupOrder) => {
        const groupValues = [literal(group.slug), literal(group.name), String(groupOrder)];
        const subcategories = group.subcategories ?? [];
        if (subcategories.length === 0) rows.push(`  (${[...category, ...groupValues, "null", "null", "null"].join(", ")})`);
        subcategories.forEach((sub, subOrder) => {
          rows.push(`  (${[...category, ...groupValues, literal(sub.slug), literal(sub.name), String(subOrder)].join(", ")})`);
        });
      });
    });
  return [TAXONOMY_BEGIN, "insert into taxonomy_source values", `${rows.join(",\n")};`, TAXONOMY_END].join("\n");
}
