import type { Db } from "../src/db";

/**
 * Turns the catalogue of a seeded test database into one SQL script an
 * owner can run in the Supabase SQL editor, so a new project shows the same
 * SAMPLE catalogue as mock mode (packages/api-client). It is a copy of
 * rows, ids included, so products keep their links to categories, images,
 * prices and stock.
 *
 * The script protects whatever is already there:
 *   - it stops, changing nothing, unless migration 0004 has been applied
 *     and the catalogue is empty (no products, categories or brands);
 *   - it runs in one transaction, so a failure leaves nothing half-loaded.
 *
 * The values are SAMPLE data. Prices and stock are placeholders, not
 * TRONIC's price list: once loaded and DATA_SOURCE=database is set, the
 * storefront sells at these prices.
 */

/** Tables the sample seed fills, parents before children. */
const TABLES = [
  "countries",
  "categories",
  "category_groups",
  "category_subcategories",
  "brands",
  "products",
  "product_images",
  "product_variants",
  "product_colors",
  "product_use_cases",
  "product_specifications",
  "product_country_prices",
  "stock_levels",
] as const;

const HEADER = `-- SAMPLE catalogue for a new TRONIC storefront database.
-- Generated by database/client/scripts/catalogue-sql.ts; do not edit by hand.
--
-- Run once in the Supabase SQL editor, after migrations 0001-0004.
-- It stops without changing anything if the catalogue already has
-- products, categories or brands, or if migration 0004 is missing.
--
-- These are SAMPLE products with placeholder prices and stock, the same
-- ones the storefront shows in mock mode. Replace them with the approved
-- catalogue and price list before taking real orders.

begin;

do $$
begin
  if to_regclass('public.stock_levels') is null then
    raise exception 'Run database/migrations/0004_orders.sql first: stock_levels does not exist. Nothing was changed.';
  end if;
  if exists (select 1 from products) or exists (select 1 from categories) or exists (select 1 from brands) then
    raise exception 'The catalogue already has products, categories or brands. Nothing was changed.';
  end if;
end
$$;
`;

/** Insert statements for every row of one table, in the order the rows were written. */
async function tableInserts(db: Db, table: string): Promise<string[]> {
  const columns = (
    await db.query<{ column_name: string }>(
      `select column_name from information_schema.columns
       where table_schema = 'public' and table_name = $1 and is_generated = 'NEVER'
       order by ordinal_position`,
      [table],
    )
  ).map((row) => row.column_name);
  if (columns.length === 0) throw new Error(`catalogue-sql: table ${table} not found`);

  // Postgres writes each value as a literal itself (quote_nullable), so
  // quoting and NULLs are exactly what the same Postgres will read back.
  const values = columns.map((column) => `quote_nullable("${column}"::text)`).join(", ");
  const conflict = table === "countries" ? " on conflict (code) do nothing" : "";
  const rows = await db.query<{ statement: string }>(
    `select 'insert into ${table} (${columns.join(", ")}) values (' || concat_ws(', ', ${values}) || ')${conflict};' as statement
     from ${table} order by ctid`,
  );
  return rows.map((row) => row.statement);
}

export async function buildSampleCatalogueSql(db: Db): Promise<string> {
  const parts: string[] = [HEADER];
  for (const table of TABLES) {
    const statements = await tableInserts(db, table);
    parts.push(`-- ${table}: ${statements.length} row${statements.length === 1 ? "" : "s"}`, ...statements, "");
  }
  parts.push("commit;", "");
  return parts.join("\n");
}
