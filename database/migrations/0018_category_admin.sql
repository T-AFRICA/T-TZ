-- The banner of an active category: {"content_type", "bytes", "sha256"} rows, none otherwise.
create or replace function public_category_banner(p_slug text)
returns table (content_type text, bytes bytea, sha256 text)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select b.content_type, b.bytes, b.sha256
    from category_banners b
    join categories c on c.id = b.category_id
   where c.slug = lower(btrim(p_slug)) and c.active
$$;

-- The website's category tree: active categories, groups and subcategories
-- in their order, with each category's banner version (null without one).
create or replace function public_category_tree()
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
           'slug', c.slug, 'name', c.name, 'description', c.description,
           'banner', (select left(b.sha256, 16) from category_banners b where b.category_id = c.id),
           'groups', coalesce((
             select jsonb_agg(jsonb_build_object(
                      'slug', g.slug, 'name', g.name,
                      'subcategories', coalesce((
                        select jsonb_agg(jsonb_build_object('slug', s.slug, 'name', s.name) order by s.sort_order, s.name)
                          from category_subcategories s where s.group_id = g.id and s.active), '[]'::jsonb))
                    order by g.sort_order, g.name)
               from category_groups g where g.category_id = c.id and g.active), '[]'::jsonb))
         order by c.sort_order, c.name), '[]'::jsonb)
    from categories c
   where c.active
$$;

