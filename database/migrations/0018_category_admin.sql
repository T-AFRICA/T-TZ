-- 0018_category_admin.sql — categories and brands from the Central Admin (DRAFT).
--
-- Forward-only, additive. Exercised only against a disposable PGlite
-- database with a Supabase role shim (database/client/tests); applying it
-- to a Supabase project needs owner approval. Requires 0001, 0003 and 0016.
-- Safe to run again.
--
-- Owner decisions 2026-11-20:
--   * The website's categories (menu, homepage, footer, category pages)
--     come from this database, edited in the Central Admin. To change
--     nothing on day one, this fills the database with the list the website
--     shows today (packages/country-config): names, order, descriptions,
--     every group and subcategory. A name an administrator has changed is
--     never overwritten when this runs again.
--   * Nothing is deleted: a category, group or subcategory is hidden. A
--     web address (slug) never changes once made.
--   * A category can have a banner photo, uploaded from the admin and
--     stored here, served by the storefront at /media/categories/<slug>.
--   * Brands are created and renamed from the admin.
--
-- Rules:
--   * Visitors keep reading active categories through the policies of
--     0003; the banner of an active category is the only new public read.
--   * The admin functions are executable by service_role only (signed
--     requests from the Central Admin, verified by the storefront).
--   * Every change is recorded in catalogue_changes, once per request.
--   * New rows of the list get ids made from their slugs, the same in every
--     database, so the SAMPLE catalogue script (which copies ids) still fits.

