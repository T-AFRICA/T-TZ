select distinct on (s.category_slug) taxonomy_uuid('category:' || s.category_slug), s.category_slug, s.category_name, s.category_description, s.category_order
  from taxonomy_source s
 order by s.category_slug
on conflict (slug) do update
  set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order, updated_at = now()
  where categories.edited_at is null;

insert into category_groups (id, category_id, slug, name, sort_order)
select distinct on (c.id, s.group_slug) taxonomy_uuid('group:' || s.category_slug || '/' || s.group_slug), c.id, s.group_slug, s.group_name, s.group_order
  from taxonomy_source s
  join categories c on c.slug = s.category_slug
 where s.group_slug is not null
 order by c.id, s.group_slug
on conflict (category_id, slug) do update
  set name = excluded.name, sort_order = excluded.sort_order, updated_at = now()
  where category_groups.edited_at is null;

insert into category_subcategories (id, group_id, slug, name, sort_order)
select taxonomy_uuid('sub:' || s.category_slug || '/' || s.group_slug || '/' || s.sub_slug), g.id, s.sub_slug, s.sub_name, s.sub_order
  from taxonomy_source s
  join categories c on c.slug = s.category_slug
  join category_groups g on g.category_id = c.id and g.slug = s.group_slug
 where s.sub_slug is not null
on conflict (group_id, slug) do update
  set name = excluded.name, sort_order = excluded.sort_order, updated_at = now()
  where category_subcategories.edited_at is null;

