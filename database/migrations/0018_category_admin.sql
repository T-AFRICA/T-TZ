-- A version 4 style uuid made from a text, the same in every database.
create or replace function taxonomy_uuid(p_text text)
returns uuid
language sql
immutable
set search_path = public, pg_temp
as $$
  select (substr(h, 1, 8) || '-' || substr(h, 9, 4) || '-4' || substr(h, 14, 3) || '-8' || substr(h, 18, 3) || '-' || substr(h, 21, 12))::uuid
    from (select md5(p_text) as h) x
$$;

