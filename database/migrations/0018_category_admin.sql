-- Every category, group, subcategory and brand, hidden ones too, with how
-- many products sit in each (all, and live).
create or replace function admin_category_tree(p_country char(2))
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with counted as (
    select p.category_id, p.group_id, p.subcategory_id, p.brand_id, p.active from products p
  )
  select jsonb_build_object(
    'categories', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', c.id, 'slug', c.slug, 'name', c.name, 'description', c.description,
               'sort_order', c.sort_order, 'active', c.active,
               'banner', (select jsonb_build_object('sha256', b.sha256, 'updated_at', b.updated_at) from category_banners b where b.category_id = c.id),
               'products', (select count(*) from counted x where x.category_id = c.id),
               'live', (select count(*) from counted x where x.category_id = c.id and x.active),
               'groups', coalesce((
                 select jsonb_agg(jsonb_build_object(
                          'id', g.id, 'slug', g.slug, 'name', g.name, 'sort_order', g.sort_order, 'active', g.active,
                          'products', (select count(*) from counted x where x.group_id = g.id),
                          'live', (select count(*) from counted x where x.group_id = g.id and x.active),
                          'subcategories', coalesce((
                            select jsonb_agg(jsonb_build_object(
                                     'id', s.id, 'slug', s.slug, 'name', s.name, 'sort_order', s.sort_order, 'active', s.active,
                                     'products', (select count(*) from counted x where x.subcategory_id = s.id),
                                     'live', (select count(*) from counted x where x.subcategory_id = s.id and x.active))
                                   order by s.sort_order, s.name)
                              from category_subcategories s where s.group_id = g.id), '[]'::jsonb))
                        order by g.sort_order, g.name)
                   from category_groups g where g.category_id = c.id), '[]'::jsonb))
             order by c.sort_order, c.name)
        from categories c), '[]'::jsonb),
    'brands', coalesce((
      select jsonb_agg(jsonb_build_object('id', b.id, 'slug', b.slug, 'name', b.name,
                                          'products', (select count(*) from counted x where x.brand_id = b.id))
                       order by b.name)
        from brands b), '[]'::jsonb))
$$;

-- Creates (p_id null) or edits a category, group or subcategory.
--   p_level   'category' | 'group' | 'subcategory'
--   p_parent  the category of a new group, the group of a new subcategory
--   p_input   {"slug" (new only), "name", "description" (categories), "sort_order", "active"}
-- Returns {"ok": true, "replayed": bool, "id", "slug"} or
--   {"ok": false, "code": "invalid_request" | "not_found" | "slug_taken"}
create or replace function admin_save_taxonomy(p_country char(2), p_level text, p_id uuid, p_parent uuid, p_input jsonb, p_actor uuid, p_request uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_change       catalogue_changes%rowtype;
  v_name         text := btrim(coalesce(p_input ->> 'name', ''));
  v_slug         text := lower(btrim(coalesce(p_input ->> 'slug', '')));
  v_description  text := nullif(btrim(coalesce(p_input ->> 'description', '')), '');
  v_order        integer;
  v_active       boolean;
  v_id           uuid;
  v_final_slug   text;
begin
  if p_actor is null or p_request is null or jsonb_typeof(p_input) is distinct from 'object'
     or p_level not in ('category', 'group', 'subcategory')
     or char_length(v_name) not between 2 and 60
     or char_length(coalesce(v_description, '')) > 200
     or (p_level <> 'category' and v_description is not null)
     or jsonb_typeof(p_input -> 'sort_order') is distinct from 'number'
     or jsonb_typeof(p_input -> 'active') is distinct from 'boolean'
     or (p_id is null and (v_slug !~ '^[a-z0-9]+(-[a-z0-9]+)*$' or char_length(v_slug) > 60))
     or (p_id is null and p_level <> 'category' and p_parent is null) then
    return jsonb_build_object('ok', false, 'code', 'invalid_request');
  end if;
  if (p_input ->> 'sort_order')::numeric <> trunc((p_input ->> 'sort_order')::numeric)
     or (p_input ->> 'sort_order')::numeric not between 0 and 10000 then
    return jsonb_build_object('ok', false, 'code', 'invalid_request');
  end if;
  v_order := (p_input ->> 'sort_order')::integer;
  v_active := (p_input ->> 'active')::boolean;

  select * into v_change from catalogue_changes c where c.request_id = p_request;
  if found then
    if v_change.action <> 'category.save' then
      return jsonb_build_object('ok', false, 'code', 'invalid_request');
    end if;
    return jsonb_build_object('ok', true, 'replayed', true, 'id', v_change.detail ->> 'id', 'slug', v_change.detail ->> 'slug');
  end if;

  begin
    if p_level = 'category' then
      if p_id is null then
        -- Shop by Use is the website's own section, not a category.
        if v_slug = 'shop-by-use' or exists (select 1 from categories c where c.slug = v_slug) then
          return jsonb_build_object('ok', false, 'code', 'slug_taken');
        end if;
        insert into categories (slug, name, description, sort_order, active, edited_at)
        values (v_slug, v_name, v_description, v_order, v_active, now())
        returning id, slug into v_id, v_final_slug;
      else
        update categories set name = v_name, description = v_description, sort_order = v_order, active = v_active,
                              edited_at = now(), updated_at = now()
         where id = p_id returning id, slug into v_id, v_final_slug;
      end if;
    elsif p_level = 'group' then
      if p_id is null then
        if not exists (select 1 from categories c where c.id = p_parent) then
          return jsonb_build_object('ok', false, 'code', 'not_found');
        end if;
        if exists (select 1 from category_groups g where g.category_id = p_parent and g.slug = v_slug) then
          return jsonb_build_object('ok', false, 'code', 'slug_taken');
        end if;
        insert into category_groups (category_id, slug, name, sort_order, active, edited_at)
        values (p_parent, v_slug, v_name, v_order, v_active, now())
        returning id, slug into v_id, v_final_slug;
      else
        update category_groups set name = v_name, sort_order = v_order, active = v_active, edited_at = now(), updated_at = now()
         where id = p_id returning id, slug into v_id, v_final_slug;
      end if;
    else
      if p_id is null then
        if not exists (select 1 from category_groups g where g.id = p_parent) then
          return jsonb_build_object('ok', false, 'code', 'not_found');
        end if;
        if exists (select 1 from category_subcategories s where s.group_id = p_parent and s.slug = v_slug) then
          return jsonb_build_object('ok', false, 'code', 'slug_taken');
        end if;
        insert into category_subcategories (group_id, slug, name, sort_order, active, edited_at)
        values (p_parent, v_slug, v_name, v_order, v_active, now())
        returning id, slug into v_id, v_final_slug;
      else
        update category_subcategories set name = v_name, sort_order = v_order, active = v_active, edited_at = now(), updated_at = now()
         where id = p_id returning id, slug into v_id, v_final_slug;
      end if;
    end if;
  exception when unique_violation then
    return jsonb_build_object('ok', false, 'code', 'slug_taken');
  end;

  if v_id is null then
    return jsonb_build_object('ok', false, 'code', 'not_found');
  end if;
  insert into catalogue_changes (action, detail, actor_id, request_id)
  values ('category.save', jsonb_build_object('level', p_level, 'id', v_id, 'slug', v_final_slug, 'name', v_name, 'active', v_active), p_actor, p_request);
  return jsonb_build_object('ok', true, 'replayed', false, 'id', v_id, 'slug', v_final_slug);
end
$$;

-- Creates (p_id null) or renames a brand. The slug is made from the name
-- when it is created and never changes. Returns
--   {"ok": true, "replayed": bool, "id"} or {"ok": false, "code": "invalid_request" | "not_found" | "name_taken"}
create or replace function admin_save_brand(p_country char(2), p_id uuid, p_name text, p_actor uuid, p_request uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_change  catalogue_changes%rowtype;
  v_name    text := btrim(coalesce(p_name, ''));
  v_slug    text;
  v_id      uuid;
begin
  if p_actor is null or p_request is null or char_length(v_name) not between 1 and 60 then
    return jsonb_build_object('ok', false, 'code', 'invalid_request');
  end if;
  select * into v_change from catalogue_changes c where c.request_id = p_request;
  if found then
    if v_change.action <> 'brand.save' then
      return jsonb_build_object('ok', false, 'code', 'invalid_request');
    end if;
    return jsonb_build_object('ok', true, 'replayed', true, 'id', v_change.detail ->> 'id');
  end if;
  if exists (select 1 from brands b where lower(b.name) = lower(v_name) and b.id is distinct from p_id) then
    return jsonb_build_object('ok', false, 'code', 'name_taken');
  end if;
  begin
    if p_id is null then
      v_slug := trim(both '-' from regexp_replace(lower(v_name), '[^a-z0-9]+', '-', 'g'));
      if v_slug = '' then
        v_slug := 'brand';
      end if;
      if exists (select 1 from brands b where b.slug = v_slug) then
        v_slug := v_slug || '-' || substr(md5(p_request::text), 1, 6);
      end if;
      insert into brands (slug, name) values (v_slug, v_name) returning id into v_id;
    else
      update brands set name = v_name where id = p_id returning id into v_id;
    end if;
  exception when unique_violation then
    return jsonb_build_object('ok', false, 'code', 'name_taken');
  end;
  if v_id is null then
    return jsonb_build_object('ok', false, 'code', 'not_found');
  end if;
  insert into catalogue_changes (action, detail, actor_id, request_id)
  values ('brand.save', jsonb_build_object('id', v_id, 'name', v_name), p_actor, p_request);
  return jsonb_build_object('ok', true, 'replayed', false, 'id', v_id);
end
$$;

-- Sets (p_bytes given) or removes (p_bytes null) a category's banner.
-- Returns {"ok": true, "replayed": bool} or {"ok": false, "code": "invalid_request" | "not_found"}
create or replace function admin_set_category_banner(p_country char(2), p_category uuid, p_content_type text, p_bytes bytea, p_actor uuid, p_request uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if p_actor is null or p_request is null or p_category is null
     or (p_bytes is not null and (p_content_type not in ('image/jpeg', 'image/png', 'image/webp') or octet_length(p_bytes) not between 100 and 1048576)) then
    return jsonb_build_object('ok', false, 'code', 'invalid_request');
  end if;
  if exists (select 1 from catalogue_changes c where c.request_id = p_request) then
    return jsonb_build_object('ok', true, 'replayed', true);
  end if;
  if not exists (select 1 from categories c where c.id = p_category) then
    return jsonb_build_object('ok', false, 'code', 'not_found');
  end if;
  if p_bytes is null then
    delete from category_banners where category_id = p_category;
  else
    insert into category_banners (category_id, content_type, bytes, sha256)
    values (p_category, p_content_type, p_bytes, encode(sha256(p_bytes), 'hex'))
    on conflict (category_id) do update
      set content_type = excluded.content_type, bytes = excluded.bytes, sha256 = excluded.sha256, updated_at = now();
  end if;
  insert into catalogue_changes (action, detail, actor_id, request_id)
  values ('category.banner', jsonb_build_object('id', p_category, 'removed', p_bytes is null), p_actor, p_request);
  return jsonb_build_object('ok', true, 'replayed', false);
end
$$;

-- A category's banner for administrators (a hidden category's too): {"content_type", "data" (base64)} or null.
create or replace function admin_get_category_banner(p_country char(2), p_category uuid)
returns jsonb
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select jsonb_build_object('content_type', b.content_type, 'data', translate(encode(b.bytes, 'base64'), E'\n', ''))
    from category_banners b where b.category_id = p_category
$$;

